<?php
/**
 * Settings → Shadcn AI: the one screen a consumer might ever need, and only
 * when their site cannot be verified from the outside (local and staging
 * URLs) — everyone else gets their token silently on first use and never
 * comes here. Shows which server this site talks to, whether a token is
 * held, and a paste box for a manually issued one. A quiet corner of
 * Settings, not a top-level menu — the feature configures itself.
 *
 * @package ShadcnBlocks
 * @since 1.0.0
 */

namespace ShadcnBlocks\ShadcnAi;

defined( 'ABSPATH' ) || exit;

use ShadcnBlocks\Traits\SingletonTrait;

class SettingsPage {
	use SingletonTrait;

	const SITE_TOKEN_ACTION = 'shadcn_ai_save_site_token';

	protected function __construct() {
		add_action( 'admin_menu', array( $this, 'add_admin_menu' ) );
		add_action( 'admin_post_' . self::SITE_TOKEN_ACTION, array( $this, 'handle_save_site_token' ) );
	}

	public function add_admin_menu() {
		add_options_page(
			__( 'Shadcn AI', 'yaycommerce-blocks-for-shadcn-ui' ),
			__( 'Shadcn AI', 'yaycommerce-blocks-for-shadcn-ui' ),
			'manage_options',
			'shadcn-ai',
			array( $this, 'render_settings_page' )
		);
	}

	/**
	 * Store a manually issued site token. Submitting an empty box forgets the
	 * held token, which forces a fresh self-registration on the next AI
	 * request.
	 */
	public function handle_save_site_token() {
		if ( ! current_user_can( 'manage_options' ) ) {
			wp_die( esc_html__( 'Insufficient permissions.', 'yaycommerce-blocks-for-shadcn-ui' ) );
		}

		check_admin_referer( self::SITE_TOKEN_ACTION );

		$token = isset( $_POST['site_token'] ) ? sanitize_text_field( wp_unslash( $_POST['site_token'] ) ) : '';

		if ( '' === $token ) {
			Client::forget_token();
		} else {
			Client::store_token( $token );
		}

		wp_safe_redirect( admin_url( 'options-general.php?page=shadcn-ai' ) );
		exit;
	}

	public function render_settings_page() {
		if ( ! current_user_can( 'manage_options' ) ) {
			return;
		}
		$site_token = Client::token();
		?>
		<div class="wrap">
			<h1><?php esc_html_e( 'Shadcn AI', 'yaycommerce-blocks-for-shadcn-ui' ); ?></h1>

			<p>
				<?php esc_html_e( 'AI layouts are generated by:', 'yaycommerce-blocks-for-shadcn-ui' ); ?>
				<code><?php echo esc_html( Client::server_url() ); ?></code>
			</p>
			<p>
				<?php esc_html_e( 'Site token:', 'yaycommerce-blocks-for-shadcn-ui' ); ?>
				<strong>
					<?php
					echo '' === $site_token
						? esc_html__( 'not yet — the site registers itself the first time someone uses Shadcn AI', 'yaycommerce-blocks-for-shadcn-ui' )
						: esc_html__( 'held', 'yaycommerce-blocks-for-shadcn-ui' );
					?>
				</strong>
			</p>

			<form method="post" action="<?php echo esc_url( admin_url( 'admin-post.php' ) ); ?>">
				<input type="hidden" name="action" value="<?php echo esc_attr( self::SITE_TOKEN_ACTION ); ?>" />
				<?php wp_nonce_field( self::SITE_TOKEN_ACTION ); ?>
				<table class="form-table" role="presentation">
					<tr>
						<th scope="row">
							<label for="shadcn_ai_site_token_field">
								<?php esc_html_e( 'Site Token (manual)', 'yaycommerce-blocks-for-shadcn-ui' ); ?>
							</label>
						</th>
						<td>
							<input
								type="password"
								id="shadcn_ai_site_token_field"
								name="site_token"
								value=""
								class="regular-text"
								autocomplete="off"
							/>
							<p class="description">
								<?php esc_html_e( 'Only needed when this site cannot be verified from the outside (local or staging URLs) — paste a token issued by the AI service administrator. Submitting an empty box forgets the held token, forcing a fresh registration on the next request.', 'yaycommerce-blocks-for-shadcn-ui' ); ?>
							</p>
						</td>
					</tr>
				</table>
				<?php submit_button( __( 'Save Site Token', 'yaycommerce-blocks-for-shadcn-ui' ) ); ?>
			</form>
		</div>
		<?php
	}
}
