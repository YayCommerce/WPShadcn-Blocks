/**
 * Icon manifest generator.
 *
 * Reads the curated slug list, pulls each SVG from `lucide-static`, normalizes
 * it (currentColor, no hard-coded width/height so CSS controls size, single
 * line, stable class + aria-hidden), then writes TWO generated artifacts that
 * MUST stay in sync:
 *   - src/shared/icons/icon-registry.js  (editor manifest, ES module)
 *   - inc/icon-map.php                    (frontend PHP map)
 *
 * Run: `npm run icons` (also runs automatically via `prebuild`).
 * Fails loudly (exit 1) if any slug is missing from lucide-static.
 */
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const require = createRequire( import.meta.url );
const __dirname = path.dirname( fileURLToPath( import.meta.url ) );
const pluginRoot = path.resolve( __dirname, '..' );

const lucideIconsDir = path.join(
	path.dirname( require.resolve( 'lucide-static/package.json' ) ),
	'icons'
);

const { CURATED_ICONS } = await import(
	pathToFileURL( path.join( pluginRoot, 'src/shared/icons/curated-icons.mjs' ) ).href
);

const slugs = [ ...new Set( CURATED_ICONS ) ];

/**
 * Normalize a raw lucide-static SVG string into a compact, size-agnostic,
 * theme-colored inline SVG safe for both editor injection and PHP output.
 *
 * @param {string} raw  Raw SVG file contents.
 * @param {string} slug Icon slug (for the stable class + aria-label).
 * @return {string} Normalized single-line SVG.
 */
function normalize( raw, slug ) {
	let svg = raw
		// Drop the license comment.
		.replace( /<!--[\s\S]*?-->/g, '' )
		// Remove width/height from the ROOT <svg> only (so CSS/inline size
		// controls dimensions). Child shapes like <rect> MUST keep their own
		// width/height or they collapse to zero area and render blank.
		.replace( /<svg\b[^>]*>/, ( tag ) =>
			tag.replace( /\s(width|height)="[^"]*"/g, '' )
		)
		// Replace lucide's own class with a stable, theme-scoped class.
		.replace( /\sclass="[^"]*"/, ` class="shadcn-icon__svg shadcn-icon__svg--${ slug }"` )
		// Collapse all whitespace runs to single spaces, trim between tags.
		.replace( /\s*\n\s*/g, ' ' )
		.replace( />\s+</g, '><' )
		.trim();

	// Ensure decorative + accessible defaults on the root <svg>.
	if ( ! /aria-hidden=/.test( svg ) ) {
		svg = svg.replace( /^<svg /, '<svg aria-hidden="true" focusable="false" ' );
	}

	return svg;
}

const entries = [];
const missing = [];

for ( const slug of slugs ) {
	const file = path.join( lucideIconsDir, `${ slug }.svg` );
	if ( ! fs.existsSync( file ) ) {
		missing.push( slug );
		continue;
	}
	entries.push( [ slug, normalize( fs.readFileSync( file, 'utf8' ), slug ) ] );
}

if ( missing.length ) {
	console.error(
		`\n[build-icon-manifest] ${ missing.length } slug(s) not found in lucide-static:\n  ${ missing.join( '\n  ' ) }\n`
	);
	process.exit( 1 );
}

// Deterministic order for stable diffs.
entries.sort( ( a, b ) => a[ 0 ].localeCompare( b[ 0 ] ) );

const GEN_NOTE = 'GENERATED by scripts/build-icon-manifest.mjs — do not edit. Run `npm run icons`.';

// --- Write JS registry (editor manifest) ---
const jsBody = entries
	.map( ( [ slug, svg ] ) => `\t${ JSON.stringify( slug ) }: ${ JSON.stringify( svg ) },` )
	.join( '\n' );

const jsOut = `/**\n * ${ GEN_NOTE }\n *\n * Editor-side icon manifest: slug -> normalized inline SVG (currentColor).\n */\nexport const ICON_REGISTRY = {\n${ jsBody }\n};\n\nexport const ICON_SLUGS = Object.keys( ICON_REGISTRY );\n`;

fs.writeFileSync(
	path.join( pluginRoot, 'src/shared/icons/icon-registry.js' ),
	jsOut,
	'utf8'
);

// --- Write PHP map (frontend) ---
const phpBody = entries
	.map( ( [ slug, svg ] ) => `\t'${ slug.replace( /'/g, "\\'" ) }' => '${ svg.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }',` )
	.join( '\n' );

const phpOut = `<?php\n/**\n * ${ GEN_NOTE }\n *\n * Frontend icon map: slug => normalized inline SVG (currentColor).\n *\n * @package ShadcnBlocks\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n${ phpBody }\n);\n`;

fs.writeFileSync( path.join( pluginRoot, 'inc/icon-map.php' ), phpOut, 'utf8' );

console.log(
	`[build-icon-manifest] Wrote ${ entries.length } icons -> src/shared/icons/icon-registry.js + inc/icon-map.php`
);
