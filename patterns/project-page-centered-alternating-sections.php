<p class="has-text-align-center has-lg-font-size">We started in the wheelhouse rather than in a design file, riding every route in both directions across two weeks in February. The crews had already solved the problem informally — a shared notebook, a radio channel, the habit of calling ahead — and the software had simply never been asked to match them.</p>
