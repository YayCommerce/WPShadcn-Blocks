<div class="wp-block-column" style="flex-basis:67%"><!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">Kestrel had been growing ferns and hellebores outside Frome for eleven years, and every surface of the business had been made on a different afternoon. Pot labels were hand-lettered, the price list lived in a spreadsheet that only one person could open, and orders arrived by telephone between ten and four on weekdays. Nothing was broken exactly, but nothing agreed with anything else either.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted-foreground","fontSize":"base"} -->
<p class="has-muted-foreground-color has-text-color has-base-font-size">We started in the potting shed rather than in the browser. Over three visits we catalogued the two hundred and forty varieties actually in production, photographed every one of them against the same sheet of grey card, and rewrote the care notes in the language the growers already used with customers at the gate. That inventory became the spine of everything that followed: the labels, the catalogue and the shop all read from one list instead of three.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"textColor":"muted-foreground","fontSize":"base"} -->
<p class="has-muted-foreground-color has-text-color has-base-font-size">The identity itself is deliberately quiet: a single condensed wordmark, one warm green, and a label stock that survives being watered twice a day for a season without turning to pulp. The storefront reuses that type at three sizes and nothing else, so a plant page is mostly photograph, price and the two lines a customer needs before deciding. It launched a fortnight before the spring rush and carried it — orders through the site outran the telephone by the second weekend, and the growers spent March in the glasshouse rather than beside the answering machine.</p>
