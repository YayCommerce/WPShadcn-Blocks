<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-xs-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">Challenge</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">Tern Line carries about four hundred thousand passengers a year, most of them in eleven weeks of summer. The service had grown one pier at a time, and so had its signs: enamel boards from the sixties, a laminated A4 sheet taped over the timetable at Harrow Quay, and a departure screen at the mainland terminal that listed vessel names rather than islands. Regulars knew which queue was theirs. Nobody else did.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">The operations team could describe the problem in one number. Nineteen percent of summer sailings left late, and the harbourmaster's log put most of that on passengers boarding the wrong vessel and having to be walked back down the ramp. We were asked for new signs. What the service actually needed was a single way of naming things that held from the ticket in a hand to the board above a gangway.</p>
