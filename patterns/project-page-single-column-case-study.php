<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-xs-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">Process</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">We rode the boats for two weeks before we drew anything, at six in the morning and again at the last sailing, and we counted every question asked at a ticket window. Four questions accounted for most of them: which boat, which pier, how long, and whether a bicycle could come. Those four became the fixed order of every sign, every screen and every line of the printed timetable, and nothing was allowed to answer them out of sequence.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">Colour does the rest of the work. Each island holds one hue that never appears anywhere else in the system, printed on the ticket stub, painted on the gangway post and repeated as a band across the top of the departure board. Crew learned it in a morning. We tested the boards in horizontal rain at Harrow Quay in February, moved the type up a size, and dropped the vessel names to a whisper below the destination.</p>
