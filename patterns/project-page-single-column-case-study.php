<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-xs-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">Outcome</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">The system went up over one winter, pier by pier, so that no sailing lost a board it still depended on. By the following August late departures had fallen to seven percent, and the harbourmaster's log recorded eleven misboardings across the whole season against a hundred and forty the year before. Ticket-window questions dropped far enough that the second window at Cardan Pier now opens only on bank holidays.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">Two things outlived the brief. The island colours have been adopted by the tourist board for its walking maps, which was never asked for and is the part we are most pleased about. And the pocket timetable, printed as a run of eighty thousand and given away free, sold out of its paid reprint by the end of the season.</p>
