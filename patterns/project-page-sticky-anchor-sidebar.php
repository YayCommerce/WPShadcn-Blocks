<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-sm-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">01 — The brief</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">Halden Havn runs one route with seven stops, and until last spring every stop explained itself differently. Two piers had a printed timetable under scratched acrylic, one had a chalkboard the crew updated when they remembered, and the landing at Sørvik had nothing at all — regulars there watched a community group for delay notices and hoped somebody had posted. The brief we were handed ran to a single sentence: make the route legible to a person who has never taken it.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">We said early on that this was not a logo problem. Ridership was steady and the boats were genuinely liked; what nobody trusted was the information around them. So we scoped the work around three moments instead — deciding to travel, finding the right pier, and knowing a boat is actually coming — and agreed that anything we drew had to earn its place in one of the three or not be drawn.</p>
<!-- /wp:paragraph -->

