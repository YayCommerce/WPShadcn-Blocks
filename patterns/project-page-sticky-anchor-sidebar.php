<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-sm-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">03 — The sign system</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">One family of signs replaced the eleven arrangements we counted. It comes in three sizes — a pier marker readable from the water, a departure panel at eye height, and a small plate for the gangway — and each carries the same four facts in the same order: where you are, where the boat goes next, when it leaves, and what to do if it does not. Everything else moved to a single printed card kept behind the ticket desk.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">The piers were renamed after the places people actually say rather than the administrative names on the county register, which took two council meetings and was the single change passengers mentioned most. Panels are enamelled steel with a matte face, chosen after a salt-spray test killed the printed vinyl we had specified first, and the departure strip is a magnetic insert the crew can change from the deck in under a minute.</p>
<!-- /wp:paragraph -->

