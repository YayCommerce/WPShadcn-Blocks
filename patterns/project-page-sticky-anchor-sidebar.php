<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-sm-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">02 — Field study</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">We rode the whole route eleven times over three weeks, in weather that ran from flat calm to a February gale, and stood on each pier for the half hour before a departure. The failure we kept recording was not missing information but contradictory information: a timetable on the shelter wall, a second one on the ticket machine, and a third inside an app the county had commissioned in 2019 and quietly stopped updating.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">Twenty-two passenger interviews and six with the crew who sell tickets on board filled in what watching could not. Crew were correcting the schedule by hand most weeks. Commuters had memorised the route years ago and read nothing. Visitors, roughly a third of summer traffic, were the only group reading the signs closely — and they were the group the signs served worst.</p>
<!-- /wp:paragraph -->

