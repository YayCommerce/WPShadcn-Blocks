<h2 class="wp-block-heading has-muted-foreground-color has-text-color has-sm-font-size" style="font-weight:600;letter-spacing:0.12em;text-transform:uppercase">04 — Ticketing and results</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">The ticket screen on the pier and the one in the crew's handheld now open on the same view: the next sailing, in type large enough to read at arm's length in rain, with a single button to buy a seat on it. Return journeys, multi-day passes and the bicycle supplement all still exist, but they sit one level down, where the four per cent of passengers who need them can find them without slowing everyone else.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph {"style":{"typography":{"lineHeight":"1.7"}},"fontSize":"lg"} -->
<p class="has-lg-font-size" style="line-height:1.7">Six months after the last panel went up, boarding time at the three busiest piers is down by about ninety seconds a sailing, and the crew log fewer than one route question per crossing where they used to log six or seven. The harbour office has taken over the timetable inserts itself, which was the part of the handover we were least sure of and the part that has needed us least.</p>
