<!-- wp:paragraph {"fontSize":"lg"} -->
<p class="has-lg-font-size">No flash, no tripod, one lens. Sodium lamps gave a colour cast that no filter fixed cleanly, so the decision was made early to let it sit in the print rather than fight it. Exposures ran long enough that anyone moving through the frame arrived as a smear, which turned out to be the honest record of how the street actually felt at that hour.</p>
