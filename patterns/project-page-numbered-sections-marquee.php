<p class="has-lg-font-size">Four thousand exposures became three hundred, then eighty, then thirty-eight. The rule that did most of the cutting was simple: a frame stayed only if it said something the frame before it had not already said. Twelve good photographs of the same loading bay make one photograph and eleven arguments for keeping busy.</p>
